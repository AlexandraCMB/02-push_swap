#include "libft.h"

void	ft_lstadd_back(t_list **lst, t_list *new)
{
	t_list	*temp;

	if (!lst || !new)
		return ;
	temp = ft_lstlast(*lst);
	if (*lst == NULL)
	{
		new->next = NULL;
		*lst = new;
	}
	else
		temp->next = new;
}
